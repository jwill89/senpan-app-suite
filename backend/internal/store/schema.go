package store

import (
	"context"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// Schema is the schema the migrations build, as the committed backend/schema.sql
// holds it: a new database in a temporary folder is migrated, and every table,
// index and trigger it then has is written out with the SQL that made it, tables
// first, each kind by name. goose's own version table is left out.
//
// `go run ./cmd/schema-gen` writes it; TestSchemaIsCurrent fails when the
// committed copy is not what the migrations build now, so every schema change
// shows in review.
func Schema(ctx context.Context) (string, error) {
	dir, err := os.MkdirTemp("", "senpan-schema-")
	if err != nil {
		return "", err
	}
	defer os.RemoveAll(dir) //nolint:errcheck // a temporary folder; the schema is the result
	st, err := New(ctx, filepath.Join(dir, "schema.sqlite"))
	if err != nil {
		return "", err
	}
	defer st.Close() //nolint:errcheck // read-only from here; runs before the folder goes

	version, err := st.SchemaVersion(ctx)
	if err != nil {
		return "", err
	}
	rows, err := st.read.QueryContext(ctx, `SELECT sql FROM sqlite_master
		WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' AND name != 'goose_db_version'
		ORDER BY CASE type WHEN 'table' THEN 0 WHEN 'index' THEN 1 WHEN 'trigger' THEN 2 ELSE 3 END, name`)
	if err != nil {
		return "", err
	}
	defer rows.Close() //nolint:errcheck // rows.Err below reports a failed read

	var b strings.Builder
	fmt.Fprintf(&b, "-- The schema the migrations build, at v%d. Generated by `go run ./cmd/schema-gen`\n", version)
	b.WriteString("-- from internal/store/baseline.sql and internal/store/migrations; never edit it.\n")
	for rows.Next() {
		var sql string
		if err := rows.Scan(&sql); err != nil {
			return "", err
		}
		b.WriteString("\n" + sql + ";\n")
	}
	return b.String(), rows.Err()
}
